"""Provider orchestration with safe, ordered failover."""
from __future__ import annotations

import logging
from collections.abc import AsyncIterator

from app.ai.llm import LLMs, llm as default_llm

logger = logging.getLogger(__name__)


class AllProvidersFailed(RuntimeError):
    """Raised when no configured LLM provider can complete a response."""


class LLMFallbackManager:
    """Try providers in configured priority order and return one complete answer.

    The manager buffers each provider's output before returning it. This is
    intentional: if a provider fails halfway through a streamed response, no
    partial text has been sent to the user, so the next model cannot accidentally
    append a second model's answer to the first model's partial answer.
    """

    def __init__(self, provider_engine: LLMs | None = None):
        self.provider_engine = provider_engine or default_llm

    async def generate(self, prompt: str) -> dict[str, str]:
        failures: list[str] = []
        chain = self.provider_engine.get_fallback_chain()

        if not chain:
            raise AllProvidersFailed("No LLM providers are configured.")

        for provider_name, stream_function in chain:
            logger.info("Attempting LLM provider: %s", provider_name)
            collected: list[str] = []

            try:
                stream = stream_function(prompt)
                async for token in stream:
                    if token:
                        collected.append(token)

                answer = "".join(collected).strip()
                if not answer:
                    raise RuntimeError("Provider returned an empty response.")

                logger.info("LLM response generated by %s", provider_name)
                return {
                    "answer": answer,
                    "provider": provider_name,
                }

            except Exception as exc:
                # Provider SDKs expose different exception classes. At this
                # boundary, any provider request failure triggers the next
                # configured provider; detailed errors stay in server logs.
                logger.warning(
                    "LLM provider %s failed; trying next provider. Error: %s",
                    provider_name,
                    exc,
                )
                failures.append(f"{provider_name}: {type(exc).__name__}")

        raise AllProvidersFailed(
            "All configured LLM providers failed. " + "; ".join(failures)
        )



